function sortValue(item, key) {
  if (key === "rank") return item.rank;
  if (key === "name") return item.e.name.toLowerCase();
  if (key.startsWith("track:")) return item.e.tracks[key.slice(6)] ?? -1;
  return item.e[key] ?? -1;
}
