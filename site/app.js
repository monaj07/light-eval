try { const saved = localStorage.getItem("theme"); if (saved) document.documentElement.dataset.theme = saved; } catch { /* storage unavailable */ }
themeButton.addEventListener("click", () => {
  const next = isDark() ? "light" : "dark";
  document.documentElement.dataset.theme = next;
  try { localStorage.setItem("theme", next); } catch { /* storage unavailable */ }
  render();
});
matchMedia("(prefers-color-scheme: dark)").addEventListener("change", () => { if (!document.documentElement.dataset.theme) render(); });

