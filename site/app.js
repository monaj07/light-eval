/* ---------- chart: horizontal bars, ranges and stacks ---------- */
function bars(el, rows, o) {
  const W = Math.max(300, el.clientWidth), small = W < 560;
  const labelW = small ? 0 : Math.min(260, Math.max(150, Math.max(...rows.map((r) => r.label.length)) * 7 + 40));
  const rowH = small ? 46 : 30, m = { t: 22, b: 30 };
  const left = small ? 8 : labelW + 12, right = W - (small ? 60 : 80);
  const H = m.t + rows.length * rowH + m.b;
  const x = (v) => left + (right - left) * (v - o.min) / (o.max - o.min);
  let s = svgOpen(W, H, o.title);
  for (const t of o.ticks) {
    s += `<line x1="${x(t)}" x2="${x(t)}" y1="${m.t - 6}" y2="${H - m.b}" stroke="var(--grid)"/>`;
    s += `<text x="${x(t)}" y="${H - m.b + 16}" text-anchor="middle" font-size="11.5">${o.tick(t)}</text>`;
  }
  for (const ref of o.refs || []) {
    s += `<line x1="${x(ref.v)}" x2="${x(ref.v)}" y1="${m.t - 10}" y2="${H - m.b}" stroke="var(--bad)" stroke-dasharray="4 4"/>`;
    s += `<text x="${x(ref.v) + 4}" y="${m.t - 10}" font-size="11" style="fill:var(--bad)">${esc(ref.label)}</text>`;
  }
  rows.forEach((row, i) => {
    const top = m.t + i * rowH, barY = small ? top + 22 : top + 8, bh = small ? 12 : 13;
    if (small) s += `<text x="${left}" y="${top + 14}" font-size="12" style="fill:var(--ink);font-weight:600">${esc(row.label)}</text>`;
    else s += `<text x="${labelW}" y="${top + 19}" text-anchor="end" font-size="12.5" style="fill:var(--ink)">${esc(row.label)}</text>`;
    s += `<g class="pt" tabindex="0" data-tip="${tip(row.tip)}"${row.href ? ` data-href="${esc(row.href)}"` : ""}>`;
    s += `<rect x="${left}" y="${top}" width="${right - left}" height="${rowH}" fill="transparent"/>`;
    for (const seg of row.segs) {
      if (seg.dot) s += `<circle class="mark" cx="${x(seg.v)}" cy="${barY + bh / 2}" r="5.5" fill="${seg.color}"/>`;
      else s += `<rect class="mark" x="${x(seg.from)}" y="${barY}" width="${Math.max(2, x(seg.to) - x(seg.from))}" height="${bh}" rx="3" fill="${seg.color}"/>`;
    }
    s += `<text x="${x(row.end) + 8}" y="${barY + bh - 2}" font-size="12" style="fill:var(--ink)">${esc(row.value)}</text></g>`;
  });
  el.innerHTML = s + "</svg>";
}
function entryLabel(e) { return `${e.name}${e.thinking === "on" ? " · on" : " · off"}`; }

/* ---------- chart: dumbbell (thinking off to on) ---------- */
function dumbbell(el, rows, key, o) {
  const W = Math.max(300, el.clientWidth), small = W < 560;
  const labelW = small ? 0 : 190, rowH = small ? 44 : 34, m = { t: 10, b: 30 };
  const left = small ? 14 : labelW + 14, right = W - 64, H = m.t + rows.length * rowH + m.b;
  const x = o.log
    ? (v) => left + (right - left) * (Math.log10(v) - Math.log10(o.min)) / (Math.log10(o.max) - Math.log10(o.min))
    : (v) => left + (right - left) * (v - o.min) / (o.max - o.min);
  let s = svgOpen(W, H, o.title);
  for (const t of o.ticks) {
    s += `<line x1="${x(t)}" x2="${x(t)}" y1="${m.t}" y2="${H - m.b}" stroke="var(--grid)"/>`;
    s += `<text x="${x(t)}" y="${H - m.b + 16}" text-anchor="middle" font-size="11.5">${o.tick(t)}</text>`;
  }
  rows.forEach((row, i) => {
    const top = m.t + i * rowH, cy = small ? top + 30 : top + rowH / 2;
    if (small) s += `<text x="${left - 6}" y="${top + 13}" font-size="12" style="fill:var(--ink);font-weight:600">${esc(row.name)}</text>`;
    else s += `<text x="${labelW}" y="${cy + 4}" text-anchor="end" font-size="12.5" style="fill:var(--ink)">${esc(row.name)}</text>`;
    const a = row.off?.[key], b = row.on?.[key];
    if (a != null && b != null) s += `<line x1="${x(a)}" x2="${x(b)}" y1="${cy}" y2="${cy}" stroke="var(--muted)" stroke-width="3" opacity=".5"/>`;
    for (const mode of ["off", "on"]) {
      const e = row[mode]; if (!e || e[key] == null) continue;
      s += `<g class="pt" tabindex="0" data-tip="${tip(entryTip(e))}" data-href="#/model/${esc(e.model_slug)}">
        <circle cx="${x(e[key])}" cy="${cy}" r="14" fill="transparent"/><circle class="mark" cx="${x(e[key])}" cy="${cy}" r="7" fill="var(--${mode})"/></g>`;
    }
    const last = [row.off?.[key], row.on?.[key]].filter((v) => v != null);
    s += `<text x="${x(Math.max(...last)) + 12}" y="${cy + 4}" font-size="12" style="fill:var(--ink)">${esc(o.fmt(row))}</text>`;
  });
  el.innerHTML = s + "</svg>";
}

