function niceTicks(max) {
  const step = [1, 2, 5, 10, 20, 25, 50, 100, 200].find((s) => max / s <= 6) || 500;
  return Array.from({ length: Math.floor(max / step) + 1 }, (_, i) => i * step);
}
function threadChart(el, pairs) {
  const W = Math.max(300, el.clientWidth), small = W < 560;
  const labelW = small ? 0 : 220, rowH = small ? 46 : 32, m = { t: 8, b: 30 };
  const left = small ? 10 : labelW + 12, right = W - (small ? 120 : 170), H = m.t + pairs.length * rowH + m.b;
  const vals = pairs.flatMap((p) => [p.e2.median_s, p.e4.median_s]);
  const lo = Math.min(...vals) / 1.3, hi = Math.max(...vals) * 1.3;
  const x = (v) => left + (right - left) * (Math.log10(v) - Math.log10(lo)) / (Math.log10(hi) - Math.log10(lo));
  let s = svgOpen(W, H, "Time per case at 2 and 4 threads");
  for (const t of logTicks(lo, hi).filter((t) => [1, 3, 10, 30, 60, 180, 600].includes(t))) {
    s += `<line x1="${x(t)}" x2="${x(t)}" y1="${m.t}" y2="${H - m.b}" stroke="var(--grid)"/><text x="${x(t)}" y="${H - m.b + 16}" text-anchor="middle" font-size="11.5">${tickLabel(t)}</text>`;
  }
  pairs.forEach(({ e2, e4 }, i) => {
    const top = m.t + i * rowH, cy = small ? top + 30 : top + rowH / 2;
    const label = entryLabel(e4);
    if (small) s += `<text x="${left}" y="${top + 13}" font-size="12" style="fill:var(--ink);font-weight:600">${esc(label)}</text>`;
    else s += `<text x="${labelW}" y="${cy + 4}" text-anchor="end" font-size="12.5" style="fill:var(--ink)">${esc(label)}</text>`;
    const change = e4.median_s / e2.median_s - 1, color = `var(--${e4.thinking})`;
    const tipHtml = `<h4>${logo(e4.model)}${esc(e4.name)}</h4><div class="muted">${modeName(e4)}</div><dl><dt>2 threads</dt><dd>${dur(e2.median_s)} · ${pct(e2.accuracy)}</dd><dt>4 threads</dt><dd>${dur(e4.median_s)} · ${pct(e4.accuracy)}</dd><dt>Prompt processing</dt><dd>${num(e2.prefill_tok_s)} → ${num(e4.prefill_tok_s)} tokens/s</dd><dt>Generation</dt><dd>${num(e2.decode_tok_s)} → ${num(e4.decode_tok_s)} tokens/s</dd><dt>Peak CPU</dt><dd>${num(e2.temp_peak, 0)} → ${num(e4.temp_peak, 0)} °C</dd></dl>`;
    s += `<g class="pt" tabindex="0" data-tip="${tip(tipHtml)}"><rect x="${left}" y="${top}" width="${right - left}" height="${rowH}" fill="transparent"/>
      <line x1="${x(e2.median_s)}" x2="${x(e4.median_s)}" y1="${cy}" y2="${cy}" stroke="${color}" stroke-width="2"/>
      <circle cx="${x(e2.median_s)}" cy="${cy}" r="6" fill="var(--panel)" stroke="${color}" stroke-width="2"/>
      <circle class="mark" cx="${x(e4.median_s)}" cy="${cy}" r="6" fill="${color}"/>
      <text x="${Math.max(x(e2.median_s), x(e4.median_s)) + 12}" y="${cy + 4}" font-size="12" style="fill:${change < 0 ? "var(--good)" : "var(--bad)"};font-weight:600">${Math.abs(change * 100).toFixed(0)}% ${change < 0 ? "faster" : "slower"}</text></g>`;
  });
  el.innerHTML = s + "</svg>" + `<div class="legend" style="margin-top:6px"><span><i class="ring"></i> 2 threads</span><span><i></i> 4 threads (thinking off)</span><span><i class="on"></i> 4 threads (thinking on)</span></div>`;
}

