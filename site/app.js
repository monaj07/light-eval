const primary = () => D.entries.filter((e) => e.primary);
function ranked(list) {
  return list.map((e) => ({
    e, rank: 1 + list.filter((o) => o !== e && Math.min(...o.pass_accuracy) > Math.max(...e.pass_accuracy) + 1e-9).length,
  }));
}
function filtered() {
  let list = F.threads === "main" ? primary() : D.entries.filter((e) => e.threads === 2);
  if (F.thinking !== "all") list = list.filter((e) => e.thinking === F.thinking);
  if (F.fits) list = list.filter((e) => e.memory === "fits");
  if (F.q) list = list.filter((e) => `${e.name} ${e.model} ${family(e.model).maker}`.toLowerCase().includes(F.q.toLowerCase()));
  return list;
}
function trackSplit(e, track) {
  const ids = D.cases.filter((c) => c.track === track);
  const part = (kind) => {
    const set = ids.filter((c) => c.difficulty === kind);
    return { passed: set.reduce((s, c) => s + (e.case_pass[c.id] ?? 0), 0), total: set.length };
  };
  return { control: part("control"), challenge: part("challenge") };
}

