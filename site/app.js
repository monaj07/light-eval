function pageCompare(aId, bId) {
  const list = D.entries;
  const p = primary().sort((x, y) => y.accuracy - x.accuracy);
  const a = list.find((e) => e.id === aId) || p[0];
  const b = list.find((e) => e.id === bId && e !== a) || p.find((e) => e !== a);
  const option = (sel) => list.map((e) => `<option value="${esc(e.id)}"${e === sel ? " selected" : ""}>${esc(e.name)} · thinking ${e.thinking} · ${e.threads} threads</option>`).join("");
  const metric = (label, va, vb, fmt, better) => {
    const d = va != null && vb != null ? vb - va : null;
    const good = d == null || Math.abs(d) < 1e-9 ? "" : (better === "high" ? d > 0 : d < 0) ? "delta-pos" : "delta-neg";
    return `<tr><td>${label}</td><td class="num">${fmt(va)}</td><td class="num">${fmt(vb)}</td><td class="num ${good}">${d == null || Math.abs(d) < 1e-9 ? "—" : fmt.delta ? fmt.delta(d) : (d > 0 ? "+" : "") + fmt(d)}</td></tr>`;
  };
  const pts = (v) => pct(v); pts.delta = (d) => `${d > 0 ? "+" : ""}${d.toFixed(0)} pts`;
  const sec = (v) => dur(v); sec.delta = (d) => `${d > 0 ? "+" : "−"}${dur(Math.abs(d))}`;
  const mem = (v) => gb(v); mem.delta = (d) => `${d > 0 ? "+" : "−"}${gb(Math.abs(d))}`;
  const deg = (v) => (v == null ? "—" : `${v.toFixed(0)} °C`); deg.delta = (d) => `${d > 0 ? "+" : "−"}${Math.abs(d).toFixed(0)} °C`;
  const cnt = (v) => num(v, v % 1 ? 1 : 0); cnt.delta = (d) => `${d > 0 ? "+" : "−"}${num(Math.abs(d), Math.abs(d) % 1 ? 1 : 0)}`;
  let both = 0, onlyA = 0, onlyB = 0, neither = 0;
  const cells = D.cases.map((c) => {
    const fa = a.case_pass[c.id], fb = b.case_pass[c.id];
    if (fa == null || fb == null) return `<span class="cell" style="background:repeating-linear-gradient(135deg, transparent 0 3px, var(--sunk) 3px 6px)" tabindex="0" data-tip="${tip(`<h4>${esc(c.id)}</h4><p class="muted">One of the two can't attempt this track.</p>`)}"></span>`;
    const pa = fa >= .5, pb = fb >= .5;
    let color, word;
    if (pa && pb) { both++; color = "var(--good)"; word = "both passed"; }
    else if (pa) { onlyA++; color = "var(--off)"; word = `only ${a.name} (${a.thinking})`; }
    else if (pb) { onlyB++; color = "var(--on)"; word = `only ${b.name} (${b.thinking})`; }
    else { neither++; color = "var(--bad)"; word = "neither passed"; }
    return `<span class="cell" style="background:${color}" tabindex="0" data-tip="${tip(`<h4>${esc(c.id)}</h4><div class="muted">${trackName(c.track)} · ${c.difficulty}</div><p style="margin:6px 0 0">${esc(c.title)}</p><dl><dt>${esc(a.name)} · ${a.thinking}</dt><dd>${Math.round(fa * a.passes)} of ${a.passes}</dd><dt>${esc(b.name)} · ${b.thinking}</dt><dd>${Math.round(fb * b.passes)} of ${b.passes}</dd></dl><p style="margin:6px 0 0"><b>${esc(word)}</b></p>`)}"></span>`;
  }).join("");
  app.innerHTML = `<h1>Compare</h1><p class="lede">Any two results side by side, down to individual cases.</p>
    <div class="vs"><label>Result A<br><select id="ca">${option(a)}</select></label><span class="mid">vs</span><label>Result B<br><select id="cb">${option(b)}</select></label></div>
    <section class="section grid grid-2">
      <div class="card table-wrap"><table class="lb"><thead><tr><th>Metric</th><th class="num">${logo(a.model)} A</th><th class="num">${logo(b.model)} B</th><th class="num">B − A</th></tr></thead><tbody>
        ${metric("Accuracy", a.accuracy, b.accuracy, pts, "high")}${metric("Challenges", a.challenge_accuracy, b.challenge_accuracy, pts, "high")}
        ${D.tracks.map((t) => metric(t.name, a.tracks[t.id], b.tracks[t.id], pts, "high")).join("")}
        ${metric("Time per case", a.median_s, b.median_s, sec, "low")}${metric("Peak memory", a.peak_mem_gb, b.peak_mem_gb, mem, "low")}
        ${metric("Peak CPU", a.temp_peak, b.temp_peak, deg, "low")}${metric("Timeouts", a.timeouts, b.timeouts, cnt, "low")}</tbody></table></div>
      <div class="card pad"><h3>Case by case</h3>
        <div class="swatches" style="margin:0 0 10px"><span><i style="background:var(--good)"></i>both pass: ${both}</span><span><i style="background:var(--off)"></i>only A: ${onlyA}</span><span><i style="background:var(--on)"></i>only B: ${onlyB}</span><span><i style="background:var(--bad)"></i>neither: ${neither}</span></div>
        <div class="casegrid">${cells}</div><p class="note">A case counts as passed when it passed in at least half of a result's passes. ${D.tracks.map((t) => t.name).join(" · ")}, 13 cases each.</p></div></section>`;
  const go = () => { location.hash = `#/compare/${document.getElementById("ca").value}/${document.getElementById("cb").value}`; };
  document.getElementById("ca").addEventListener("change", go);
  document.getElementById("cb").addEventListener("change", go);
}

