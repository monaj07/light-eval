function family(model) {
  return M.families.find((f) => new RegExp(f.match, "i").test(model)) || M.default;
}
function logo(model, size = "") {
  const f = family(model);
  if (f.logo) return `<span class="logo img ${size}" title="${esc(f.maker || f.family)}" aria-hidden="true"><img src="${esc(f.logo)}" alt=""></span>`;
  return `<span class="logo ${size}" style="background:${esc(f.color)}" title="${esc(f.maker || f.family)}" aria-hidden="true">${esc(f.mark)}</span>`;
}
function isDark() {
  const set = document.documentElement.dataset.theme;
  return set ? set === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;
}
/* Sequential blue ramp for accuracy cells, separate steps for each theme. */
function heat(v) {
  if (v == null) return "";
  const t = Math.max(0, Math.min(1, v / 100));
  const light = isDark() ? 17 + t * 38 : 96 - t * 58;
  const sat = isDark() ? 55 : 72;
  const ink = isDark() ? (t > .55 ? "#fff" : "#e8e7e2") : (light < 62 ? "#fff" : "#16324f");
  return `background:hsl(213 ${sat}% ${light}%);color:${ink}`;
}
function passColor(f) {
  if (f == null) return "var(--sunk)";
  if (f >= 0.999) return "var(--good)";
  if (f <= 0.001) return "var(--bad)";
  return "var(--warn)";
}
const css = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();

function tags(e, { mode = false } = {}) {
  const out = [];
  if (mode) out.push(`<span class="mode ${e.thinking}">${e.thinking}</span>`);
  if (e.flag) out.push(`<span class="tag bad">${esc(e.flag)}</span>`);
  if (e.threads_note) out.push(`<span class="tag">${esc(e.threads_note)}</span>`);
  if (e.memory === "out") out.push(`<span class="tag bad">doesn't fit</span>`);
  if (e.memory === "tight") out.push(`<span class="tag warn">tight memory</span>`);
  for (const t of D.tracks) if (!e.supported_tracks.includes(t.id)) out.push(`<span class="tag">no ${t.name.toLowerCase()}</span>`);
  if (!e.official) out.push(`<span class="tag">exploratory</span>`);
  return out.join("");
}
/* How far a result's accuracy could move: its 95% interval when the suite reports one (suite 1.8,
   one pass), otherwise its range across passes. Ranks tie when these overlap. */
function range(e) {
  if (e.interval) {
    const [lo, hi] = e.interval;
    return { lo, hi, label: "95% interval", text: `${Math.round(lo)}–${Math.round(hi)}%` };
  }
  const lo = Math.min(...e.pass_accuracy), hi = Math.max(...e.pass_accuracy);
  return { lo, hi, label: "Across passes", text: e.passes > 1 ? (Math.round(lo) === Math.round(hi) ? `${Math.round(lo)}% in every pass` : `${Math.round(lo)}–${Math.round(hi)}%`) : "one pass" };
}
function tierRows(e) {
  return D.tiers.filter((t) => t !== "control").map((t) => `<dt>${tierName(t)}</dt><dd>${pct(e[`${t}_accuracy`])}</dd>`).join("");
}
function extraRows(e) {
  return (e.injection ? `<dt>Planted instructions followed</dt><dd>${count(e.injection.followed)} of ${count(e.injection.cases)}</dd>` : "")
    + (e.repeat ? `<dt>Repeats that changed</dt><dd>${e.repeat.changed} of ${e.repeat.cases}</dd>` : "");
}
function splitRows(sp) {
  return D.tiers.map((t) => `<dt>${tierName(t)}</dt><dd>${count(sp[t].passed)} of ${sp[t].total}</dd>`).join("");
}
function memText(e) {
  if (e.peak_mem_gb == null) return "—";
  const word = { fits: "fits", tight: "tight", out: "doesn't fit" }[e.memory] || "";
  return `${gb(e.peak_mem_gb)}${e.mem_exact ? "" : "≈"}${word ? ` (${word})` : ""}`;
}

