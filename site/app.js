/* ---------- formatting ---------- */
const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
const pct = (v, digits = 0) => (v == null ? "—" : `${v.toFixed(digits)}%`);
const dur = (s) => (s == null ? "—" : s < 60 ? `${s.toFixed(1)} s` : `${(s / 60).toFixed(1)} min`);
const gb = (v) => (v == null ? "—" : `${v.toFixed(1)} GB`);
const num = (v, d = 1) => (v == null ? "—" : v.toFixed(d));
const plural = (n, word) => `${n} ${n === 1 ? word : word.endsWith("s") ? `${word}es` : `${word}s`}`;
const modeName = (e) => `Thinking ${e.thinking}`;
const trackName = (id) => D.tracks.find((t) => t.id === id)?.name ?? id;
const shortTrack = { arithmetic: "Arith", structured: "Struct", agent: "Agent", vision: "Vision", context: "Context" };

function family(model) {
  return M.families.find((f) => new RegExp(f.match, "i").test(model)) || M.default;
}
function logo(model, size = "") {
  const f = family(model);
  const inner = f.logo ? `<img src="${esc(f.logo)}" alt="">` : esc(f.mark);
  return `<span class="logo ${size}" style="background:${esc(f.color)}" title="${esc(f.maker || f.family)}" aria-hidden="true">${inner}</span>`;
}
function isDark() {
  const set = document.documentElement.dataset.theme;
  return set ? set === "dark" : matchMedia("(prefers-color-scheme: dark)").matches;
}
/* Sequential blue ramp for accuracy cells, separate steps for each theme. */
function heat(v) {
  if (v == null) return "";
  const t = Math.max(0, Math.min(1, v / 100));
  const light = isDark() ? 17 + t * 38 : 96 - t * 58;
  const sat = isDark() ? 55 : 72;
  const ink = isDark() ? (t > .55 ? "#fff" : "#e8e7e2") : (light < 62 ? "#fff" : "#16324f");
  return `background:hsl(213 ${sat}% ${light}%);color:${ink}`;
}
function passColor(f) {
  if (f == null) return "var(--sunk)";
  if (f >= 0.999) return "var(--good)";
  if (f <= 0.001) return "var(--bad)";
  return "var(--warn)";
}
const css = (name) => getComputedStyle(document.documentElement).getPropertyValue(name).trim();

function tags(e, { mode = false } = {}) {
  const out = [];
  if (mode) out.push(`<span class="mode ${e.thinking}">${e.thinking}</span>`);
  if (e.flag) out.push(`<span class="tag bad">${esc(e.flag)}</span>`);
  if (e.threads_note) out.push(`<span class="tag">${esc(e.threads_note)}</span>`);
  if (e.memory === "out") out.push(`<span class="tag bad">doesn't fit</span>`);
  if (e.memory === "tight") out.push(`<span class="tag warn">tight memory</span>`);
  for (const t of D.tracks) if (!e.supported_tracks.includes(t.id)) out.push(`<span class="tag">no ${t.name.toLowerCase()}</span>`);
  if (!e.official) out.push(`<span class="tag">exploratory</span>`);
  return out.join("");
}
function range(e) {
  const lo = Math.min(...e.pass_accuracy), hi = Math.max(...e.pass_accuracy);
  return { lo, hi, text: e.passes > 1 ? (Math.round(lo) === Math.round(hi) ? `${Math.round(lo)}% in every pass` : `${Math.round(lo)}–${Math.round(hi)}%`) : "one pass" };
}
function memText(e) {
  if (e.peak_mem_gb == null) return "—";
  const word = { fits: "fits", tight: "tight", out: "doesn't fit" }[e.memory] || "";
  return `${gb(e.peak_mem_gb)}${e.mem_exact ? "" : "≈"}${word ? ` (${word})` : ""}`;
}

/* ---------- tooltips ---------- */
function tip(html) { tips.push(html); return tips.length - 1; }
function entryTip(e) {
  const r = range(e);
  const trackCells = D.tracks.map((t) => {
    const v = e.tracks[t.id];
    return `<span style="${v == null ? "background:var(--sunk);color:var(--muted)" : heat(v)}">${shortTrack[t.id]}<br>${v == null ? "n/a" : Math.round(v)}</span>`;
  }).join("");
  return `<h4>${logo(e.model)}${esc(e.name)}</h4>
    <div class="muted">${modeName(e)} · ${e.threads} threads · ${plural(e.passes, "pass")}</div>
    <dl><dt>Accuracy</dt><dd><b>${pct(e.accuracy)}</b> (${num(e.score, e.score % 1 ? 1 : 0)} of ${e.supported_cases} cases)</dd>
    <dt>Across passes</dt><dd>${r.text}</dd>
    <dt>Challenges</dt><dd>${pct(e.challenge_accuracy)}</dd>
    <dt>Time per case</dt><dd>${dur(e.median_s)}</dd>
    <dt>Peak memory</dt><dd>${memText(e)}</dd>
    <dt>Peak CPU</dt><dd>${e.temp_peak == null ? "—" : `${e.temp_peak.toFixed(0)} °C`}</dd>
    <dt>Hit the time limit</dt><dd>${num(e.timeouts, e.passes > 1 && e.timeouts % 1 ? 1 : 0)}</dd></dl>
    <div class="tt-tracks">${trackCells}</div>
    ${tags(e) ? `<div style="margin-top:6px">${tags(e)}</div>` : ""}`;
}
let tipOwner = null, lastPointer = "mouse";
function showTip(el, x, y) {
  const html = tips[+el.dataset.tip];
  if (html == null) return;
  tipOwner = el;
  tipBox.innerHTML = html;
  tipBox.hidden = false;
  if (x == null) { const r = el.getBoundingClientRect(); x = r.left + r.width / 2; y = r.top; }
  placeTip(x, y);
}
function placeTip(x, y) {
  const w = tipBox.offsetWidth, h = tipBox.offsetHeight, pad = 12;
  let left = x + 14, top = y - h - 12;
  if (left + w > innerWidth - pad) left = Math.max(pad, x - w - 14);
  if (top < pad) top = Math.min(innerHeight - h - pad, y + 18);
  tipBox.style.left = `${left}px`; tipBox.style.top = `${top}px`;
}
function hideTip() { tipBox.hidden = true; tipOwner = null; }
document.addEventListener("pointerdown", (ev) => { lastPointer = ev.pointerType; });
document.addEventListener("pointerover", (ev) => {
  if (ev.pointerType === "touch") return;
  const el = ev.target.closest("[data-tip]");
  if (el) showTip(el, ev.clientX, ev.clientY);
});
document.addEventListener("pointermove", (ev) => { if (tipOwner && ev.pointerType !== "touch") placeTip(ev.clientX, ev.clientY); });
document.addEventListener("pointerout", (ev) => {
  const el = ev.target.closest("[data-tip]");
  if (el && !el.contains(ev.relatedTarget) && lastPointer !== "touch") hideTip();
});
document.addEventListener("focusin", (ev) => { const el = ev.target.closest("[data-tip]"); if (el) showTip(el); });
document.addEventListener("focusout", (ev) => { if (ev.target.closest("[data-tip]")) hideTip(); });
document.addEventListener("keydown", (ev) => {
  if (ev.key === "Escape") hideTip();
  const el = ev.target.closest?.("[data-href]");
  if (el && (ev.key === "Enter" || ev.key === " ")) { ev.preventDefault(); location.hash = el.dataset.href; }
});
document.addEventListener("click", (ev) => {
  const el = ev.target.closest("[data-tip],[data-href]");
  if (!el) { if (lastPointer === "touch") hideTip(); return; }
  // On touch, the first tap shows the details; a second tap on the same mark follows its link.
  if (lastPointer === "touch" && el.dataset.tip != null && tipOwner !== el) {
    const r = el.getBoundingClientRect();
    showTip(el, r.left + r.width / 2, r.top);
    ev.preventDefault();
    return;
  }
  if (el.dataset.href) location.hash = el.dataset.href;
});
addEventListener("scroll", () => { if (lastPointer !== "touch") hideTip(); }, { passive: true });

